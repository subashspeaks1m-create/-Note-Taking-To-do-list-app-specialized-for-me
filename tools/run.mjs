import { chromium } from '@playwright/test';
import { fixtures } from './fixtures.mjs';
const [base, outDir] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const problems = [];
// 1. Make a test PDF with bookmarks by printing HTML.
const maker = await browser.newPage();
const chapters = ['The Surprising Power of Atomic Habits', 'Make It Obvious', 'Make It Easy'];
const body = chapters.map((c, i) => `<h1>${c}</h1>` + Array.from({ length: 12 }, (_, j) => `<p>Chapter ${i + 1} paragraph ${j}. Habits are the compound interest of self-improvement. Getting 1 percent better every day counts for a lot in the long run. You do not rise to the level of your goals. You fall to the level of your systems.</p>`).join('') + '<div style="page-break-after:always"></div>').join('');
await maker.setContent(`<html><head><title>Atomic Habits Test</title></head><body style="font-family:serif">${body}</body></html>`);
await maker.pdf({ path: `${outDir}/book.pdf`, outline: true, tagged: true, displayHeaderFooter: true, headerTemplate: '<div style="font-size:9px;width:100%;text-align:center">ATOMIC HABITS</div>', footerTemplate: '<div style="font-size:9px;width:100%;text-align:center"><span class="pageNumber"></span></div>', margin: { top: '60px', bottom: '60px' } });
await maker.close();

const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await ctx.newPage();
page.on('pageerror', (e) => problems.push(`pageerror: ${e.message}`));
page.on('console', (m) => m.type() === 'error' && problems.push(`console: ${m.text()}`));
const seen = [];
await page.route('https://api.anthropic.com/**', async (route) => {
  const req = route.request();
  const body = JSON.parse(req.postData() || '{}');
  const task = body.messages[0].content[1].text;
  const section = task.startsWith('Write a complete summary') ? 'summary' : task.startsWith('Build a mind map') ? 'mindmap' : task.startsWith('Extract the insights') ? 'insights' : task.startsWith('Design a 7-day') ? 'plan7' : 'plan30';
  seen.push({ section, model: body.model, beta: req.headers()['anthropic-beta'], cache: body.messages[0].content[0].cache_control, hasBrowserHeader: req.headers()['anthropic-dangerous-direct-browser-access'], fallbacks: body.fallbacks, effort: body.output_config?.effort, hasFormat: !!body.output_config?.format, bookHasPages: body.messages[0].content[0].text?.includes('[Page 2]'), chapterMarker: body.messages[0].content[0].text?.includes('=== Chapter: Make It Obvious ==='), header: body.messages[0].content[0].text?.includes('ATOMIC HABITS\n') });
  const json = JSON.stringify(fixtures[section]);
  const chunks = json.match(/.{1,400}/gs);
  const ev = (type, data) => `event: ${type}\ndata: ${JSON.stringify({ type, ...data })}\n\n`;
  let sse = ev('message_start', { message: { id: 'msg_1', type: 'message', role: 'assistant', model: body.model, content: [], stop_reason: null, stop_sequence: null, usage: { input_tokens: 10, output_tokens: 1 } } });
  sse += ev('content_block_start', { index: 0, content_block: { type: 'text', text: '' } });
  for (const c of chunks) sse += ev('content_block_delta', { index: 0, delta: { type: 'text_delta', text: c } });
  sse += ev('content_block_stop', { index: 0 });
  sse += ev('message_delta', { delta: { stop_reason: 'end_turn', stop_sequence: null }, usage: { output_tokens: 500 } });
  sse += ev('message_stop', {});
  await new Promise((r) => setTimeout(r, 300));
  await route.fulfill({ status: 200, headers: { 'content-type': 'text/event-stream', 'access-control-allow-origin': '*' }, body: sse });
});
await page.goto(`${base}/books`, { waitUntil: 'networkidle' });
